"""Advisory wake selection for cooperating clients; never gates streamed audio.

Exact wake phrases share a short collection window. Rank reported confidence,
volume, detection time, then arrival order. A decision creates no reservation:
clients decide whether to stream, and every streamed utterance runs normally.
"""

from __future__ import annotations

import asyncio
import logging
import math
import time
import uuid
from collections import deque
from dataclasses import dataclass, replace
from typing import Any, Optional

from .tracing import emit_span

logger = logging.getLogger(__name__)

POLICY_FIRST_TO_ENDPOINT = "first_to_endpoint"  # legacy compatibility: grant immediately
POLICY_WAKE_SIGNAL = "wake_signal"
DEFAULT_POLICY = POLICY_WAKE_SIGNAL
DEFAULT_WAKE_WINDOW = 0.75
# An election stops waiting for a device once its chance of claiming falls below this.
LIKELY_TO_CLAIM = 0.1
# How many of a pair's latest gaps between claims are kept.
RECENT_GAPS = 100


@dataclass(frozen=True)
class DeviceAnnounce:
    device_id: str
    registered_at: float


@dataclass(frozen=True)
class Device:
    device_id: str
    registered_at: float


@dataclass(frozen=True)
class WakeClaim:
    claim_id: str  # generated by the client, unique within its socket
    device_id: str
    wake_word: str
    confidence: Optional[float]
    heard_at: Optional[float]
    volume: Optional[float]
    claimed_at: float
    # Trace only: when it arrived, its place among the election's claims, and who sent it.
    received_ns: int = 0
    arrival: int = 0
    device_name: Optional[str] = None
    session_id: Optional[str] = None


@dataclass
class _ClaimRecord:
    """What the election's trace keeps of one claim after it is decided or withdrawn."""
    claim: WakeClaim
    outcome: Optional[str] = None  # granted | denied | withdrawn | error
    sent: Optional[bool] = None
    settled: bool = False


class Bus:
    """The message bus between devices and the arbitrator.

    Implementations deliver messages published on one connection to every other connection. The
    arbitrator publishes wake claims here for observers. Elections are local to this
    arbitrator; a distributed election requires a separate implementation.
    """

    async def publish(self, message: Any) -> None:
        """Publish *message* to every subscriber."""
        raise NotImplementedError

    async def subscribe(self) -> "asyncio.Queue[Any]":
        """Return a queue that receives every published message."""
        raise NotImplementedError


class LocalBus(Bus):
    """In-process bus: one queue per subscriber, fan-out on publish.

    Safe for concurrent use from many connections within a single Hermes instance. Not shared
    across processes. Replacing the bus alone does not distribute election state.
    """

    def __init__(self) -> None:
        self._queues: list[asyncio.Queue[Any]] = []
        self._lock = asyncio.Lock()

    async def publish(self, message: Any) -> None:
        async with self._lock:
            queues = list(self._queues)
        for q in queues:
            # Never block a publisher on a slow subscriber: drop if the queue is full.
            try:
                q.put_nowait(message)
            except asyncio.QueueFull:
                logger.debug("arbitrate: subscriber queue full, dropping message")

    async def subscribe(self) -> asyncio.Queue[Any]:
        q: asyncio.Queue[Any] = asyncio.Queue(maxsize=64)
        async with self._lock:
            self._queues.append(q)
        return q

    async def unsubscribe(self, q: asyncio.Queue[Any]) -> None:
        async with self._lock:
            self._queues = [x for x in self._queues if x is not q]


class _WakeElection:
    def __init__(self, wake_word: str, created_at: float) -> None:
        self.election_id = uuid.uuid4().hex
        self.wake_word = wake_word
        self.created_at = created_at
        self.claims: list[WakeClaim] = []
        self.done = asyncio.Event()
        # Collection ends at `deadline`, set by the first claim; `moved` wakes the finalizer
        # when a later claim or a disconnect changes it.
        self.deadline = created_at
        self.moved = asyncio.Event()
        self.winner: Optional[WakeClaim] = None
        self.immediate = False
        self.records: list[_ClaimRecord] = []
        self.created_ns = time.time_ns()
        self.decided_ns = self.created_ns
        self.decided_by: Optional[str] = None
        self.emitted = False


class Arbitrator:
    """Recommend a single wake claimant without reserving a conversation or turn."""

    def __init__(self, *, bus: Optional[Bus] = None, policy: str = DEFAULT_POLICY,
                 wake_window: float = DEFAULT_WAKE_WINDOW) -> None:
        if policy not in (POLICY_WAKE_SIGNAL, POLICY_FIRST_TO_ENDPOINT):
            raise ValueError(f"unknown arbitrate policy {policy!r}")
        if not math.isfinite(wake_window) or wake_window < 0:
            raise ValueError("wake_window must be finite and nonnegative")
        self.bus = bus or LocalBus()
        self.policy = policy
        self.wake_window = wake_window
        self._lock = asyncio.Lock()
        self._devices: dict[str, Device] = {}
        self._wake_open: dict[str, _WakeElection] = {}
        self._labels: dict[str, tuple[Optional[str], Optional[str]]] = {}  # device_id -> trace names
        self._awaiting_sent: dict[tuple[str, str], tuple[_WakeElection, _ClaimRecord]] = {}
        # Which devices hear the same utterance, learned from claims, by device name.
        # ponytail: in memory, so a restart relearns; persist if the relearning is felt.
        self._recent: list[tuple[str, str, float]] = []  # (wake word, device, claimed at)
        self._claimed: dict[str, int] = {}
        self._together: dict[tuple[str, str], int] = {}
        # Each pair's latest gaps between their claims for one utterance.
        self._skew: dict[frozenset[str], deque[float]] = {}

    async def register(self, device_id: str, *, device_name: Optional[str] = None,
                       session_id: Optional[str] = None) -> Device:
        async with self._lock:
            self._labels[device_id] = (device_name, session_id)
            device = self._devices.setdefault(device_id, Device(device_id, time.monotonic()))
        await self.bus.publish(DeviceAnnounce(device_id, device.registered_at))
        return device

    async def unregister(self, device_id: str) -> None:
        async with self._lock:
            self._devices.pop(device_id, None)
            self._labels.pop(device_id, None)
            for election in self._wake_open.values():
                election.claims = [c for c in election.claims if c.device_id != device_id]
                for record in election.records:
                    if record.claim.device_id == device_id and record.outcome is None:
                        record.outcome = "withdrawn"
                        record.settled = True
                self._reschedule(election)

    def _learn(self, claim: WakeClaim) -> None:
        """Count which devices claim a phrase within one window of this claim, and how far apart."""
        me, now = claim.device_name or claim.device_id, claim.claimed_at
        self._recent = [r for r in self._recent if now - r[2] < self.wake_window]
        heard: dict[str, float] = {}
        for word, other, at in self._recent:
            if word == claim.wake_word and other != me:
                heard.setdefault(other, at)
        self._claimed[me] = self._claimed.get(me, 0) + 1
        for other, at in heard.items():
            for pair in ((me, other), (other, me)):
                self._together[pair] = self._together.get(pair, 0) + 1
            both = frozenset((me, other))
            self._skew.setdefault(both, deque(maxlen=RECENT_GAPS)).append(now - at)
        self._recent.append((claim.wake_word, me, now))

    def _likelihood(self, claimant: str, other: str) -> float:
        """Chance *other* claims an utterance *claimant* claimed: its share of the claimant's
        claims, starting from an even prior."""
        claims = self._claimed.get(claimant, 0)
        return (min(self._together.get((claimant, other), 0), claims) + 1) / (claims + 2)

    def _wait_for(self, claimant: str, other: str) -> float:
        """How long after *claimant*'s claim *other* stays likely to claim. Each of the pair's
        past gaps that goes by without a claim makes one less likely; with none to go by, a
        claim could come at any point in the window."""
        claims = self._likelihood(claimant, other)
        gaps = sorted(self._skew.get(frozenset((claimant, other)), ()))
        for passed in range(len(gaps) + 1):
            later = (len(gaps) - passed + 1) / (len(gaps) + 1)  # chance its gap is longer still
            if claims * later / (claims * later + 1 - claims) < LIKELY_TO_CLAIM:
                return gaps[passed - 1] if passed else 0.0
        return self.wake_window

    def _reschedule(self, election: _WakeElection) -> None:
        """Collect only until no connected device that has yet to claim is still likely to."""
        if not election.claims:
            return
        claimed = {c.device_name or c.device_id for c in election.claims}
        # A device whose claim for this utterance went to an earlier election has claimed too.
        claimed |= {other for word, other, _ in self._recent if word == election.wake_word}
        waiting = {name or device_id for device_id, (name, _) in self._labels.items()} - claimed
        until = election.created_at
        for claim in election.claims:
            me = claim.device_name or claim.device_id
            for other in waiting:
                until = max(until, claim.claimed_at + self._wait_for(me, other))
        election.deadline = min(election.created_at + self.wake_window, until)
        election.moved.set()

    async def claim_wake(
        self, device_id: str, *, claim_id: str, wake_word: str,
        confidence: Optional[float] = None, heard_at: Optional[float] = None,
        volume: Optional[float] = None, track_sent: bool = False,
    ) -> tuple[bool, Optional[str], str]:
        """Return (recommended, winning device id, echoed client claim id).

        Legacy first_to_endpoint grants immediately, with no later transcript
        election. Ranking only consumes the wake request's optional signals.

        With *track_sent* the caller reports, through :meth:`note_decision_sent`, whether it sent
        the decision; the election's trace waits for that report.
        """
        async with self._lock:
            if device_id not in self._devices:
                return False, None, claim_id
            claim = WakeClaim(claim_id, device_id, wake_word, confidence, heard_at, volume,
                              time.monotonic(), time.time_ns(), 0, *self._labels.get(device_id, (None, None)))
            if self.policy == POLICY_FIRST_TO_ENDPOINT:
                election = _WakeElection(wake_word, claim.claimed_at)
                election.immediate = True
                claim = replace(claim, arrival=1)
                election.winner = claim
                election.done.set()
                record = self._enter(election, claim)
            else:
                election = self._wake_open.get(wake_word)
                if election is None or claim.claimed_at - election.created_at >= self.wake_window:
                    election = _WakeElection(wake_word, claim.claimed_at)
                    self._wake_open[wake_word] = election
                    asyncio.create_task(self._finalize_wake(election))
                    logger.info("arbitrate: wake election opened election_id=%s window_ms=%.1f",
                                election.election_id, self.wake_window * 1000)
                claim = replace(claim, arrival=len(election.records) + 1)
                record = self._enter(election, claim)
                election.claims.append(claim)
                self._learn(claim)
                self._reschedule(election)
                # Correlate timing without recording wake phrases, audio, or transcripts.
                logger.info(
                    "arbitrate: wake claim received election_id=%s device_id=%r claim_id=%r "
                    "received_unix_ms=%d received_monotonic=%.6f election_age_ms=%.1f",
                    election.election_id, device_id, claim_id, int(time.time() * 1000),
                    claim.claimed_at, (claim.claimed_at - election.created_at) * 1000)
        try:
            if election.immediate:
                winner = claim
            else:
                await self.bus.publish(claim)
                await election.done.wait()
                winner = election.winner
                logger.info(
                    "arbitrate: wake decision election_id=%s device_id=%r claim_id=%r "
                    "decision=%s winner_device_id=%r wait_ms=%.1f",
                    election.election_id, device_id, claim_id,
                    "wake_grant" if winner is claim else "wake_deny",
                    winner.device_id if winner else None, (time.monotonic() - claim.claimed_at) * 1000)
            record.outcome = "granted" if winner is claim else "denied"
            if track_sent:
                self._awaiting_sent[(device_id, claim_id)] = (election, record)
            return winner is claim, winner.device_id if winner else None, claim_id
        except asyncio.CancelledError:
            record.outcome = record.outcome or "withdrawn"
            raise
        except Exception:
            record.outcome = record.outcome or "error"
            raise
        finally:
            # A disconnected/cancelled requester must not beat live claimants.
            async with self._lock:
                election.claims = [c for c in election.claims if c is not claim]
            if not (track_sent and record.outcome in ("granted", "denied")):
                self._settle(election, record)

    def note_decision_sent(self, device_id: str, claim_id: str, sent: bool) -> None:
        """The caller reports whether it delivered the decision for a claim made with *track_sent*."""
        entry = self._awaiting_sent.pop((device_id, claim_id), None)
        if entry is not None:
            entry[1].sent = sent
            self._settle(*entry)

    def _enter(self, election: _WakeElection, claim: WakeClaim) -> _ClaimRecord:
        record = _ClaimRecord(claim)
        election.records.append(record)
        return record

    def _settle(self, election: _WakeElection, record: _ClaimRecord) -> None:
        record.settled = True
        self._emit_election(election)

    def _emit_election(self, election: _WakeElection) -> None:
        """Write the election's span once it is decided and every claim has an outcome. Reads what
        the election used; never ranks again, never changes it."""
        if election.emitted or not election.done.is_set() or not all(r.settled for r in election.records):
            return
        election.emitted = True
        try:
            attrs = {
                "election_id": election.election_id,
                "election.policy": self.policy,
                "election.window_ms": 0 if election.immediate else round(self.wake_window * 1000, 1),
                "election.claims": len(election.records),
                "election.immediate": election.immediate,
            }
            if election.decided_by:
                attrs["election.decided_by"] = election.decided_by
            if election.winner is not None:
                attrs["election.winner_claim_id"] = election.winner.claim_id
            events = []
            for record in election.records:
                claim = record.claim
                event = {"device_name": claim.device_name, "session.id": claim.session_id,
                         "claim_id": claim.claim_id, "wake_word": claim.wake_word,
                         "wake.confidence": claim.confidence, "wake.volume": claim.volume,
                         "wake.heard_at": claim.heard_at, "claim.arrival": claim.arrival,
                         "claim.outcome": record.outcome or "error"}
                if record.sent is not None:
                    event["decision.sent"] = record.sent
                events.append(("wake.claim", claim.received_ns, event))
            emit_span("voice.wake.election", election.created_ns, election.decided_ns, attrs, events=events)
        except Exception:
            logger.debug("wake election trace failed", exc_info=True)

    async def _finalize_wake(self, election: _WakeElection) -> None:
        try:
            # Waiting past the deadline is pure added latency: nobody likely to outrank the
            # best claim is left. Each claim and disconnect moves it.
            while (remaining := election.deadline - time.monotonic()) > 0:
                election.moved.clear()
                try:
                    await asyncio.wait_for(election.moved.wait(), timeout=remaining)
                except asyncio.TimeoutError:
                    break
            async with self._lock:
                if election.claims:
                    election.winner = min(election.claims, key=self._rank_wake_signal)
                    election.decided_by = self._deciding_input(election)
                election.decided_ns = time.time_ns()
                logger.info(
                    "arbitrate: wake election closed election_id=%s claimants=%d "
                    "winner_device_id=%r winner_claim_id=%r elapsed_ms=%.1f",
                    election.election_id, len(election.claims),
                    election.winner.device_id if election.winner else None,
                    election.winner.claim_id if election.winner else None,
                    (time.monotonic() - election.created_at) * 1000)
        finally:
            if self._wake_open.get(election.wake_word) is election:
                self._wake_open.pop(election.wake_word, None)
            election.done.set()
            self._emit_election(election)

    def _deciding_input(self, election: _WakeElection) -> Optional[str]:
        """The first ranking input on which the winner beat the best other claim (trace only)."""
        others = [c for c in election.claims if c is not election.winner]
        if not others:
            return None
        runner_up = min(others, key=self._rank_wake_signal)
        for name, won, lost in zip(("confidence", "volume", "detection_time", "arrival_order"),
                                   self._rank_wake_signal(election.winner),
                                   self._rank_wake_signal(runner_up)):
            if won != lost:
                return name
        return None

    @staticmethod
    def _rank_wake_signal(claim: WakeClaim) -> tuple[float, float, float, float]:
        return (-(claim.confidence if claim.confidence is not None else -1),
                -(claim.volume if claim.volume is not None else -1),
                claim.heard_at if claim.heard_at is not None else float("inf"),
                claim.claimed_at)

    @property
    def devices(self) -> dict[str, Device]:
        return dict(self._devices)
