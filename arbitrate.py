"""Advisory wake selection for cooperating clients; never gates streamed audio.

Exact wake phrases share a short collection window. Rank reported confidence,
volume, detection time, then arrival order. A decision creates no reservation:
clients decide whether to stream, and every streamed utterance runs normally.
"""

from __future__ import annotations

import asyncio
import logging
import math
import time
from dataclasses import dataclass
from typing import Any, Optional

logger = logging.getLogger(__name__)

POLICY_FIRST_TO_ENDPOINT = "first_to_endpoint"  # legacy compatibility: grant immediately
POLICY_WAKE_SIGNAL = "wake_signal"
DEFAULT_POLICY = POLICY_WAKE_SIGNAL
DEFAULT_WAKE_WINDOW = 0.25


@dataclass(frozen=True)
class DeviceAnnounce:
    device_id: str
    registered_at: float


@dataclass(frozen=True)
class Device:
    device_id: str
    registered_at: float


@dataclass(frozen=True)
class WakeClaim:
    claim_id: str  # generated by the client, unique within its socket
    device_id: str
    wake_word: str
    confidence: Optional[float]
    heard_at: Optional[float]
    volume: Optional[float]
    claimed_at: float


class Bus:
    """The message bus between devices and the arbitrator.

    Implementations deliver messages published on one connection to every other connection. The
    arbitrator publishes wake claims here for observers. Elections are local to this
    arbitrator; a distributed election requires a separate implementation.
    """

    async def publish(self, message: Any) -> None:
        """Publish *message* to every subscriber."""
        raise NotImplementedError

    async def subscribe(self) -> "asyncio.Queue[Any]":
        """Return a queue that receives every published message."""
        raise NotImplementedError


class LocalBus(Bus):
    """In-process bus: one queue per subscriber, fan-out on publish.

    Safe for concurrent use from many connections within a single Hermes instance. Not shared
    across processes. Replacing the bus alone does not distribute election state.
    """

    def __init__(self) -> None:
        self._queues: list[asyncio.Queue[Any]] = []
        self._lock = asyncio.Lock()

    async def publish(self, message: Any) -> None:
        async with self._lock:
            queues = list(self._queues)
        for q in queues:
            # Never block a publisher on a slow subscriber: drop if the queue is full.
            try:
                q.put_nowait(message)
            except asyncio.QueueFull:
                logger.debug("arbitrate: subscriber queue full, dropping message")

    async def subscribe(self) -> asyncio.Queue[Any]:
        q: asyncio.Queue[Any] = asyncio.Queue(maxsize=64)
        async with self._lock:
            self._queues.append(q)
        return q

    async def unsubscribe(self, q: asyncio.Queue[Any]) -> None:
        async with self._lock:
            self._queues = [x for x in self._queues if x is not q]


class _WakeElection:
    def __init__(self, wake_word: str, created_at: float) -> None:
        self.wake_word = wake_word
        self.created_at = created_at
        self.claims: list[WakeClaim] = []
        self.done = asyncio.Event()
        self.winner: Optional[WakeClaim] = None


class Arbitrator:
    """Recommend a single wake claimant without reserving a conversation or turn."""

    def __init__(self, *, bus: Optional[Bus] = None, policy: str = DEFAULT_POLICY,
                 wake_window: float = DEFAULT_WAKE_WINDOW) -> None:
        if policy not in (POLICY_WAKE_SIGNAL, POLICY_FIRST_TO_ENDPOINT):
            raise ValueError(f"unknown arbitrate policy {policy!r}")
        if not math.isfinite(wake_window) or wake_window < 0:
            raise ValueError("wake_window must be finite and nonnegative")
        self.bus = bus or LocalBus()
        self.policy = policy
        self.wake_window = wake_window
        self._lock = asyncio.Lock()
        self._devices: dict[str, Device] = {}
        self._wake_open: dict[str, _WakeElection] = {}

    async def register(self, device_id: str) -> Device:
        async with self._lock:
            device = self._devices.setdefault(device_id, Device(device_id, time.monotonic()))
        await self.bus.publish(DeviceAnnounce(device_id, device.registered_at))
        return device

    async def unregister(self, device_id: str) -> None:
        async with self._lock:
            self._devices.pop(device_id, None)
            for election in self._wake_open.values():
                election.claims = [c for c in election.claims if c.device_id != device_id]

    async def claim_wake(
        self, device_id: str, *, claim_id: str, wake_word: str,
        confidence: Optional[float] = None, heard_at: Optional[float] = None,
        volume: Optional[float] = None,
    ) -> tuple[bool, Optional[str], str]:
        """Return (recommended, winning device id, echoed client claim id).

        Legacy first_to_endpoint grants immediately, with no later transcript
        election. Ranking only consumes the wake request's optional signals.
        """
        async with self._lock:
            if device_id not in self._devices:
                return False, None, claim_id
            claim = WakeClaim(claim_id, device_id, wake_word, confidence, heard_at, volume,
                              time.monotonic())
            if self.policy == POLICY_FIRST_TO_ENDPOINT:
                return True, device_id, claim_id
            election = self._wake_open.get(wake_word)
            if election is None or claim.claimed_at - election.created_at >= self.wake_window:
                election = _WakeElection(wake_word, claim.claimed_at)
                self._wake_open[wake_word] = election
                asyncio.create_task(self._finalize_wake(election))
            election.claims.append(claim)
        try:
            await self.bus.publish(claim)
            await election.done.wait()
            winner = election.winner
            return winner is claim, winner.device_id if winner else None, claim_id
        finally:
            # A disconnected/cancelled requester must not beat live claimants.
            async with self._lock:
                election.claims = [c for c in election.claims if c is not claim]

    async def _finalize_wake(self, election: _WakeElection) -> None:
        try:
            await asyncio.sleep(max(0, election.created_at + self.wake_window - time.monotonic()))
            async with self._lock:
                if election.claims:
                    election.winner = min(election.claims, key=self._rank_wake_signal)
        finally:
            if self._wake_open.get(election.wake_word) is election:
                self._wake_open.pop(election.wake_word, None)
            election.done.set()

    @staticmethod
    def _rank_wake_signal(claim: WakeClaim) -> tuple[float, float, float, float]:
        return (-(claim.confidence if claim.confidence is not None else -1),
                -(claim.volume if claim.volume is not None else -1),
                claim.heard_at if claim.heard_at is not None else float("inf"),
                claim.claimed_at)

    @property
    def devices(self) -> dict[str, Device]:
        return dict(self._devices)
